	public static ModelLayerLocation layer(String id) {
		return new ModelLayerLocation(BossesMod.id("rogue_" + id), "main");
	}

	/** Registers one model layer per rogue. BossesClient calls this. */
	public static void register() {
		for (String id : IDS) {
			ModelLayerRegistry.registerModelLayer(layer(id), () -> create(id));
		}
	}

	public static LayerDefinition create(String id) {
		// Start from the player model so every part HumanoidModel looks for exists, then rebuild the parts.
		MeshDefinition mesh = HumanoidModel.createMesh(CubeDeformation.NONE, 0.0F);
		int size = switch (id) {
			case "saltjaw_rourke" -> saltjawRourke(mesh);
			case "corvina_fog_widow" -> corvinaFogWidow(mesh);
			case "iron_tide_graves" -> ironTideGraves(mesh);
			case "hollow_ronin_tsurugi" -> hollowRoninTsurugi(mesh);
			case "boilerheart_gantz" -> boilerheartGantz(mesh);
			case "nereus_vane" -> nereusVane(mesh);
			case "douglas_bullet" -> douglasBullet(mesh);
			case "gild_tesoro" -> gildTesoro(mesh);
			case "zephyr_z" -> zephyrZ(mesh);
			case "shiki_golden_lion" -> shikiGoldenLion(mesh);
			case "uta_diva" -> utaDiva(mesh);
			default -> 64;
		};
		return LayerDefinition.create(mesh, size, size);
	}

	/** The basic parts at this rogue's pivots, with no boxes of their own (the boxes are their children). */
	private static PartDefinition[] parts(MeshDefinition mesh, float[] head, float[] body, float[] arm, float[] leg) {
		PartDefinition root = mesh.getRoot();
		PartDefinition headPart = root.addOrReplaceChild("head", CubeListBuilder.create(), PartPose.offset(head[0], head[1], head[2]));
		headPart.addOrReplaceChild("hat", CubeListBuilder.create(), PartPose.ZERO);
		return new PartDefinition[] {
			headPart,
			root.addOrReplaceChild("body", CubeListBuilder.create(), PartPose.offset(body[0], body[1], body[2])),
			root.addOrReplaceChild("right_arm", CubeListBuilder.create(), PartPose.offset(arm[0], arm[1], arm[2])),
			root.addOrReplaceChild("left_arm", CubeListBuilder.create(), PartPose.offset(-arm[0], arm[1], arm[2])),
			root.addOrReplaceChild("right_leg", CubeListBuilder.create(), PartPose.offset(leg[0], leg[1], leg[2])),
			root.addOrReplaceChild("left_leg", CubeListBuilder.create(), PartPose.offset(-leg[0], leg[1], leg[2])),
		};
	}

